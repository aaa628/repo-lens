import type { AnalysisResult } from "./types";

function mermaidId(id: string) {
  return id.replace(/[^A-Za-z0-9_]/g, "_");
}

function esc(s: string) {
  return s.replace(/"/g, "'").replace(/[<>]/g, "");
}

export function toMermaid(a: AnalysisResult): string {
  const lines = ["flowchart LR"];
  const layers = ["frontend", "api", "logic", "data", "config"] as const;
  for (const layer of layers) {
    const ns = a.nodes.filter((n) => n.layer === layer);
    if (!ns.length) continue;
    lines.push(`  subgraph ${layer}["${layer.toUpperCase()}"]`);
    for (const n of ns) lines.push(`    ${mermaidId(n.id)}["${esc(n.label)}"]`);
    lines.push("  end");
  }
  for (const e of a.edges) {
    const arrow = e.grounded ? "-->" : "-.->";
    lines.push(`  ${mermaidId(e.source)} ${arrow}|"${esc(e.label)}"| ${mermaidId(e.target)}`);
  }
  lines.push(
    "  classDef frontend fill:#111111,stroke:#f5f5f5,color:#f5f5f5",
    "  classDef api fill:#1a0000,stroke:#ff1e1e,color:#ffffff",
    "  classDef logic fill:#111111,stroke:#b5b5b5,color:#e5e5e5",
    "  classDef data fill:#1a0505,stroke:#ff7070,color:#ffe5e5",
    "  classDef config fill:#0b0b0b,stroke:#6f6f6f,color:#bdbdbd",
  );
  for (const layer of layers) {
    const ids = a.nodes.filter((n) => n.layer === layer).map((n) => mermaidId(n.id));
    if (ids.length) lines.push(`  class ${ids.join(",")} ${layer}`);
  }
  return lines.join("\n");
}

export function toMarkdown(a: AnalysisResult): string {
  const { repoMeta: m } = a;
  const nodeLabel = (id: string) => a.nodes.find((n) => n.id === id)?.label ?? id;
  const blob = (file: string, line?: number) =>
    `${m.htmlUrl}/blob/${m.defaultBranch}/${file}${line ? `#L${line}` : ""}`;

  const out: string[] = [];
  out.push(`# ${m.owner}/${m.name} — Architecture Overview`, "");
  out.push(`> Generated by RepoLens · ${new Date(a.generatedBy.analyzedAt).toUTCString()} · ${a.generatedBy.model}`, "");
  if (m.description) out.push(`_${m.description}_`, "");
  out.push(a.summary, "");
  out.push(`**Tech stack:** ${m.techStack.join(", ") || "—"}  `);
  out.push(
    `**Analyzed:** ${a.stats.analyzedFiles} of ${a.stats.totalFiles} files · ${a.stats.importEdges} import edges · ${a.stats.groundedEdges}/${a.edges.length} module edges import-verified`,
    "",
  );

  out.push("## Architecture", "", "```mermaid", toMermaid(a), "```", "");
  out.push("_Solid arrows are verified by static imports; dotted arrows are inferred runtime relationships._", "");

  out.push("## Modules", "");
  for (const n of a.nodes) {
    out.push(`### ${n.label} \`${n.layer}\``, "", n.summary, "");
    if (n.files.length) out.push(n.files.map((f) => `- [\`${f}\`](${blob(f)})`).join("\n"), "");
  }

  out.push("## Bug & Code-Smell Radar", "");
  if (!a.bugs.length) out.push("No issues detected in the analyzed files.", "");
  else {
    out.push("| Severity | Issue | Location | Module |", "|---|---|---|---|");
    for (const b of a.bugs) {
      out.push(`| ${b.severity.toUpperCase()} | ${b.title} | [\`${b.file}:${b.lineHint}\`](${blob(b.file, b.line)}) | ${nodeLabel(b.nodeId)} |`);
    }
    out.push("");
    for (const b of a.bugs) {
      out.push(`#### ${b.severity.toUpperCase()} · ${b.title}`, "", `\`${b.file}:${b.lineHint}\``, "", b.description, "", `**Suggested fix:** ${b.suggestedFix}`, "");
    }
  }

  out.push("## Guided Tour", "");
  for (const w of a.walkthrough) {
    out.push(`${w.step}. **${w.title}** (${nodeLabel(w.nodeId)}) — ${w.explanation}  `, `   _Read first:_ \`${w.whatToReadFirst}\``);
  }
  out.push("");
  return out.join("\n");
}

export function download(filename: string, text: string, type = "text/markdown") {
  const blob = new Blob([text], { type: `${type};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
